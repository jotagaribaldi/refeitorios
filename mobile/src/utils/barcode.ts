// index 103 = Start A, 104 = Start B, 105 = Start C
const START_B = 104;
// Stop pattern: 2,3,3,1,1,1 + termination bar of width 2
const STOP_WIDTHS = [2,3,3,1,1,1,2];

interface Bar { x: number; width: number; }

export function encodeCode128B(text: string): { bars: Bar[]; totalWidth: number } {
  const values: number[] = [START_B];
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i) - 32;
    if (code < 0 || code > 95) throw new Error(`Character '${text[i]}' not in Code 128B`);
    values.push(code);
  }

  // Checksum
  let checksum = START_B;
  for (let i = 1; i < values.length; i++) checksum += values[i] * i;
  values.push(checksum % 103);

  const bars: Bar[] = [];
  let x = 10; // quiet zone

  const emitWidths = (widths: number[]) => {
    widths.forEach((w, i) => {
      if (i % 2 === 0) bars.push({ x, width: w }); // even = bar
      x += w;
    });
  };

  for (const v of values) emitWidths(C128[v]);
  emitWidths(STOP_WIDTHS);

  return { bars, totalWidth: x + 10 }; // +10 right quiet zone
}
